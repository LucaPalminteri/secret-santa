  "card-foreground": "ink",
  popover: "surface",
  "popover-foreground": "ink",
  primary: "cranberry",
  "primary-foreground": "surface",
  secondary: "sage",
  "secondary-foreground": "ink",
  muted: "sage",
  "muted-foreground": "muted",
  accent: "sage",
